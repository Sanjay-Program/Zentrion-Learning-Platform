/**
 * Export the local libsql database as SQL INSERT statements for
 * seeding a remote Cloudflare D1 instance.
 *
 * Usage:
 *   npm run db:dump-sql > seed.sql
 *   wrangler d1 execute zention-db --remote --file=seed.sql
 *
 * Ephemeral tables (sessions, runs, orders, progress, …) are skipped
 * so a fresh deployment gets catalogue content and demo accounts only.
 */
import { getDb } from "../src/db/client";
import * as schema from "../src/db/schema";

/** Tables that hold per-user runtime state — never seeded remotely. */
const SKIP = new Set([
  "user_sessions",
  "mfa_methods",
  "recovery_tokens",
  "login_events",
  "ai_conversations",
  "ai_messages",
  "prompt_runs",
  "agent_runs",
  "agent_steps",
  "usage_records",
  "lab_sessions",
  "lab_events",
  "lab_grades",
  "lab_evidence",
  "challenge_attempts",
  "assessment_attempts",
  "assessment_answers",
  "submissions",
  "grading_records",
  "certificates",
  "certificate_events",
  "skill_evidence",
  "portfolio_items",
  "project_submissions",
  "achievements",
  "learner_notes",
  "lesson_bookmarks",
  "notifications",
  "audit_events",
  "background_jobs",
  "webhook_events",
  "system_settings",
  "support_tickets",
  "support_ticket_messages",
  "document_chunks",
  "evaluation_results",
  "orders",
  "order_items",
  "payment_attempts",
  "payment_events",
  "subscriptions",
  "entitlements",
  "refund_requests",
  "session_registrations",
]);

function escape(value: unknown): string {
  if (value === null || value === undefined) return "NULL";
  if (typeof value === "number" || typeof value === "boolean") return String(value);
  const s = typeof value === "string" ? value : JSON.stringify(value);
  return `'${s.replace(/'/g, "''")}'`;
}

async function main() {
  const db = getDb();
  const out: string[] = [];
  out.push("-- Zentrion seed dump (content tables only)");
  out.push("-- Generated by scripts/dump-seed-sql.ts");

  for (const [name, table] of Object.entries(schema)) {
    if (!table || typeof table !== "object") continue;
    const sqlName = (table as unknown as Record<symbol, string>)[Symbol.for("drizzle:Name")];
    if (!sqlName || SKIP.has(sqlName)) continue;

    // eslint-disable-next-line @typescript-eslint/no-explicit-any
    const rows = await db.select().from(table as any).all();
    if (rows.length === 0) continue;

    out.push("");
    out.push(`-- ${sqlName} (${rows.length} rows)`);
    for (const row of rows) {
      const cols = Object.keys(row);
      const vals = cols.map((c) => escape((row as Record<string, unknown>)[c]));
      out.push(
        `INSERT INTO ${sqlName} (${cols.join(", ")}) VALUES (${vals.join(", ")});`,
      );
    }
  }

  process.stdout.write(out.join("\n") + "\n");
}

main().catch((err) => {
  console.error("Dump failed:", err);
  process.exit(1);
});
